const { contextBridge, ipcRenderer } = require('electron');

const inv = (ch) => (arg) => ipcRenderer.invoke(ch, arg);
contextBridge.exposeInMainWorld('host', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: inv('config:set'),
  setPin: (pin, oldPin) => ipcRenderer.invoke('pin:set', { pin, oldPin }),
  verifyPin: inv('pin:verify'),
  createOncePin: inv('once:create'),
  clearOncePin: inv('once:clear'),
  onOnceUsed: (fn) => ipcRenderer.on('once:used', () => fn()),
  listSources: inv('sources:list'),
  selectDisplay: inv('display:select'),
  confirmAccess: inv('access:confirm'),
  checkPermissions: inv('permissions:check'),
  requestPermission: inv('permissions:request'),
  openViewer: inv('open:viewer'),
  setSessionActive: (active) => ipcRenderer.send('session:active', active),
  onStopRequest: (fn) => ipcRenderer.on('session:stop', () => fn()),
  input: (msg) => ipcRenderer.send('input', msg),
  notify: (title, body, force) => ipcRenderer.send('notify', { title, body, force }),
  setPrivacy: inv('privacy:set'),
  setClipboard: (text) => ipcRenderer.send('clip:set', text),
  onClipboard: (fn) => ipcRenderer.on('clip:changed', (_e, t) => fn(t)),
  fileBegin: inv('file:begin'),
  fileChunk: inv('file:chunk'),
  fileEnd: inv('file:end'),
  fileShow: inv('file:show'),
  filePick: inv('file:pick'),
  fileRead: inv('file:read'),
  fileClose: inv('file:close'),
  historyGet: inv('history:get'),
  historyAdd: inv('history:add'),
  historyUpdate: inv('history:update'),
  historyClear: inv('history:clear'),
  checkUpdate: inv('update:check'),
  installUpdate: inv('update:install'),
  onUpdate: (fn) => ipcRenderer.on('update:available', (_e, i) => fn(i)),
  onUpdateProgress: (fn) => ipcRenderer.on('update:progress', (_e, p) => fn(p)),
  platform: process.platform,
});
